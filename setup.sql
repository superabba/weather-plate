-- setup.sql : Supabase SQL Editor에서 실행할 테이블 생성 및 정책 스크립트

-- 1. wx_tasks 테이블 생성
create table if not exists wx_tasks (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  title text not null,
  region text not null check (region in ('세종', '대전', '태안', '보령')),
  kind text not null check (kind in ('야외', '고소', '실내')),
  owner text not null
);

-- 2. RLS(Row Level Security) 활성화
alter table wx_tasks enable row level security;

-- 3. 공개(anon) 정책 설정 (읽기 및 쓰기 허용)
create policy "익명 사용자 읽기 허용"
  on wx_tasks for select
  to anon
  using (true);

create policy "익명 사용자 추가 허용"
  on wx_tasks for insert
  to anon
  with check (true);

